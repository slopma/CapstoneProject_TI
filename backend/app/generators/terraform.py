                    '  health_check_type         = "ELB"',
                    '  health_check_grace_period = 300',
                    '  launch_template {',
                    f'    id      = aws_launch_template.{r_id}_lt.id',
                    '    version = "$Latest"',
                    '  }',
                    '  tag {',
                    '    key                 = "Name"',
                    f'    value               = "{r_name}-ha-container-host"',
                    '    propagate_at_launch = true',
                    '  }',
                    '}',
                    '',
