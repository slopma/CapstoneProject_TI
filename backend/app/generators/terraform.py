def format_terraform_code(code: str) -> str:
    """
    Format Terraform code using `terraform fmt` CLI if available,
    otherwise fallback to clean string normalization.
    """
    tf_path = shutil.which("terraform")
    if tf_path:
        try:
            with tempfile.TemporaryDirectory() as tmp_dir:
                tmp_file = Path(tmp_dir) / "main.tf"
                tmp_file.write_text(code, encoding="utf-8")
                res = subprocess.run(
                    [tf_path, "fmt", str(tmp_file)],
                    capture_output=True,
                    text=True,
                    timeout=5,
                )
                if res.returncode == 0:
                    return tmp_file.read_text(encoding="utf-8")
        except Exception:
            pass  # Fallback to string code if subprocess fails

    # Basic Fallback Indentation Normalization
    clean_lines = []
    for line in code.splitlines():
        clean_lines.append(line.rstrip())
    return "\n".join(clean_lines) + "\n"


