def generate_aws_terraform(resources: List[Dict[str, Any]]) -> str:
    files = generate_aws_terraform_files(resources)
    return f"{files['provider.tf']}\n{files['variables.tf']}\n{files['main.tf']}\n{files['outputs.tf']}"


