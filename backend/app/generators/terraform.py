def generate_k8s_manifests(resources: List[Dict[str, Any]]) -> str:
    manifests = []
    for r in resources:
        r_name = r.get("safe_name", r.get("name"))
        kind = r.get("kind", "Deployment")
        namespace = r.get("namespace", "default")
        port = r.get("port", 80)
        image = r.get("image", "nginx:alpine")

        if kind == "Namespace":
            manifests.append(f"""apiVersion: v1
kind: Namespace
metadata:
  name: {r_name}
  labels:
    managed-by: cloudmove
---""")
        elif kind == "Secret":
            manifests.append(f"""apiVersion: v1
kind: Secret
metadata:
  name: {r_name}
  namespace: {namespace}
type: Opaque
# Secrets should be injected via Kubernetes ExternalSecrets, Vault or SealedSecrets
stringData:
  DB_PASSWORD: ""
---""")
        elif kind == "ConfigMap":
            manifests.append(f"""apiVersion: v1
kind: ConfigMap
metadata:
  name: {r_name}
  namespace: {namespace}
data:
  APP_ENV: "production"
---""")
        elif kind == "StatefulSet":
            manifests.append(f"""apiVersion: apps/v1
kind: StatefulSet
metadata:
  name: {r_name}
  namespace: {namespace}
  labels:
    app: {r_name}
    managed-by: cloudmove
spec:
  serviceName: {r_name}-headless
  replicas: 1
  selector:
    matchLabels:
      app: {r_name}
  template:
    metadata:
      labels:
        app: {r_name}
    spec:
      containers:
      - name: {r_name}
        image: {image}
        ports:
        - containerPort: {port}
---""")
        else:
            manifests.append(f"""apiVersion: apps/v1
kind: Deployment
metadata:
  name: {r_name}
  namespace: {namespace}
  labels:
    app: {r_name}
    managed-by: cloudmove
spec:
  replicas: 1
  selector:
    matchLabels:
      app: {r_name}
  template:
    metadata:
      labels:
        app: {r_name}
    spec:
      containers:
      - name: {r_name}
        image: {image}
        ports:
        - containerPort: {port}
---
apiVersion: v1
kind: Service
metadata:
  name: {r_name}-svc
  namespace: {namespace}
spec:
  selector:
    app: {r_name}
  ports:
  - port: {port}
    targetPort: {port}
---""")
    return "\n".join(manifests)