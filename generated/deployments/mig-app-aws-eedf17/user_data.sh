#!/usr/bin/env bash
# ==============================================================================
# CLOUDMOVE AUTO-SCALING CONTAINERIZED BOOTSTRAP SCRIPT (user_data.sh)
# Application : CocoaApp
# Repository  : https://github.com/slopma/CocoaApp/ (ref: main, commit: ae95bb73fba3f9d932bafe411981327185d52895)
# Architecture: High-Availability Containerized Node (ALB + Auto Scaling Group)
# ==============================================================================
set -euo pipefail
exec > >(tee /var/log/cloudmove-user-data.log | logger -t cloudmove-user-data -s 2>/dev/console) 2>&1

echo "[1/6] Configurando 2 GB de memoria Swap para soportar compilaciones pesadas en contenedores..."
if [ ! -f /swapfile ]; then
  fallocate -l 2G /swapfile || dd if=/dev/zero of=/swapfile bs=1M count=2048
  chmod 600 /swapfile
  mkswap /swapfile
  swapon /swapfile
  echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

echo "[2/6] Actualizando sistema operativo e instalando Docker Engine, Docker Compose v2 y Git..."
export DEBIAN_FRONTEND=noninteractive
apt-get update -y
apt-get install -y ca-certificates curl gnupg git jq docker.io docker-compose-v2 || apt-get install -y docker.io docker-compose git curl
systemctl enable --now docker

echo "[3/6] Clonando repositorio https://github.com/slopma/CocoaApp/ en /opt/cocoaapp..."
mkdir -p /opt/cocoaapp
if [ ! -d "/opt/cocoaapp/.git" ]; then
  git clone --branch "main" "https://github.com/slopma/CocoaApp/" /opt/cocoaapp || git clone "https://github.com/slopma/CocoaApp/" /opt/cocoaapp
fi
cd /opt/cocoaapp
if [ "ae95bb73fba3f9d932bafe411981327185d52895" != "HEAD" ] && [ "ae95bb73fba3f9d932bafe411981327185d52895" != "latest" ]; then
  git checkout "ae95bb73fba3f9d932bafe411981327185d52895" || true
fi

echo "[4/6] Generando plantilla base .env (inyecte secretos desde AWS SSM / Secrets Manager)..."
if [ ! -f /opt/cocoaapp/.env ]; then
  cat << 'EOF_ENV' > /opt/cocoaapp/.env
VITE_SUPABASE_URL=${VITE_SUPABASE_URL:-}
VITE_SUPABASE_ANON_KEY=${VITE_SUPABASE_ANON_KEY:-}
VITE_SUPABASE_SERVICE_ROLE_KEY=${VITE_SUPABASE_SERVICE_ROLE_KEY:-}
VITE_API_URL=${VITE_API_URL:-}
EOF_ENV
fi

echo "[5/6] Verificando manifiestos de contenerización (Dockerfile / Docker Compose)..."
if [ ! -f /opt/cocoaapp/Dockerfile ] && [ ! -f /opt/cocoaapp/Dockerfile.cloudmove ]; then
  cat << 'EOF_DF' > /opt/cocoaapp/Dockerfile.cloudmove
# Auto-generated by CloudMove Containerization Engine
FROM node:20-alpine
WORKDIR /app
COPY package*.json ./
RUN npm ci --omit=dev || npm install
COPY . .
EXPOSE 80
CMD ["npm", "start"]
EOF_DF
fi

if [ ! -f "/opt/cocoaapp/docker-compose.prod.yml" ]; then
  cat << 'EOF_COMPOSE' > /opt/cocoaapp/docker-compose.cloudmove.yml
# Auto-generated by CloudMove Containerization Engine (High Availability Container Stack)
services:
  backend:
    build:
      context: ./backend
      dockerfile: Dockerfile
    restart: always
    env_file:
      - .env
    ports:
      - "8000:8000"
  frontend:
    build:
      context: ./frontend-vite
      dockerfile: Dockerfile
    restart: always
    env_file:
      - .env
    ports:
      - "3000:80"
EOF_COMPOSE
  COMPOSE_FILE="docker-compose.cloudmove.yml"
else
  COMPOSE_FILE="docker-compose.prod.yml"
fi

echo "[6/6] Construyendo e iniciando contenedores con reinicio automático (resiliencia ante fallos)..."
docker compose -f "$COMPOSE_FILE" up -d --build || docker-compose -f "$COMPOSE_FILE" up -d --build

cat << EOF_SYSTEMD > /etc/systemd/system/cocoaapp-containers.service
[Unit]
Description=CloudMove Containerized Stack - CocoaApp
Requires=docker.service
After=docker.service network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
WorkingDirectory=/opt/cocoaapp
ExecStart=/usr/bin/docker compose -f $COMPOSE_FILE up -d
ExecStop=/usr/bin/docker compose -f $COMPOSE_FILE down
TimeoutStartSec=0

[Install]
WantedBy=multi-user.target
EOF_SYSTEMD

systemctl daemon-reload
systemctl enable cocoaapp-containers.service

echo "[OK] Despliegue contenerizado de 'CocoaApp' activo. Puertos: [80, 3000, 8000], Health Check: /health"
